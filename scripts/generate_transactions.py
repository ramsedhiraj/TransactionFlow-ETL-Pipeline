#!/usr/bin/env python3
"""
High-Performance Deterministic Synthetic Transaction Generator
Generates realistic financial transaction records in streaming batches.
Streams records directly to CSV without accumulating millions of rows in memory.

NOTE: All records generated by this script are entirely synthetic and fictional.
They do not represent real banking or financial data.
"""

import argparse
import csv
import math
import random
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Generator, List, Tuple

CURRENCIES = ["USD", "USD", "USD", "EUR", "EUR", "GBP", "CAD", "AUD"]
TRANSACTION_TYPES = ["PURCHASE", "PURCHASE", "TRANSFER", "WITHDRAWAL", "DEPOSIT", "REFUND", "PAYMENT"]
TRANSACTION_STATUSES = ["COMPLETED", "COMPLETED", "COMPLETED", "COMPLETED", "PENDING", "FAILED"]
MERCHANT_CATEGORIES = [
    "RETAIL",
    "GROCERY",
    "ENTERTAINMENT",
    "UTILITIES",
    "TRAVEL",
    "DINING",
    "HEALTHCARE",
    "ATM",
    "OTHER",
]
SOURCE_SYSTEMS = ["CORE_BANKING_CSV", "CARD_NETWORK_FEED", "POS_TERMINAL_STREAM"]


def generate_synthetic_record(
    rng: random.Random,
    idx: int,
    base_time: datetime,
    customer_pool_size: int,
    source_system: str,
    inject_error: bool = False,
    error_type: int = 0,
) -> dict:
    """Generate a single synthetic transaction record."""
    cust_id = f"CUST-{rng.randint(1, customer_pool_size):08d}"
    tx_time = base_time + timedelta(seconds=idx * 2 + rng.randint(0, 5))
    tx_id = f"TXN-{tx_time.strftime('%Y%m%d')}-{idx:09d}"
    src_rec_id = f"SRC-{idx:09d}"

    # Log-normal distribution for realistic transaction amounts
    amount_raw = math.exp(rng.gauss(3.5, 1.2))
    amount = round(min(max(amount_raw, 1.50), 45000.00), 2)

    currency = rng.choice(CURRENCIES)
    tx_type = rng.choice(TRANSACTION_TYPES)
    tx_status = rng.choice(TRANSACTION_STATUSES)
    m_cat = (
        rng.choice(MERCHANT_CATEGORIES)
        if tx_type in ("PURCHASE", "REFUND")
        else ("ATM" if tx_type == "WITHDRAWAL" else "TRANSFER")
    )

    record = {
        "transaction_id": tx_id,
        "source_record_id": src_rec_id,
        "source_system": source_system,
        "customer_id": cust_id,
        "transaction_timestamp": tx_time.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "transaction_amount": f"{amount:.2f}",
        "currency": currency,
        "transaction_type": tx_type,
        "transaction_status": tx_status,
        "merchant_category": m_cat,
    }

    # Inject deliberate data quality violations if requested
    if inject_error:
        if error_type == 0:
            record["transaction_id"] = ""  # Missing transaction ID
        elif error_type == 1:
            record["customer_id"] = ""  # Missing customer ID
        elif error_type == 2:
            record["transaction_amount"] = f"-{amount:.2f}"  # Negative amount
        elif error_type == 3:
            record["transaction_timestamp"] = "INVALID_TIMESTAMP_STRING"
        elif error_type == 4:
            record["currency"] = "XYZ"  # Unsupported currency
        elif error_type == 5:
            record["transaction_amount"] = "NOT_A_NUMBER"
        elif error_type == 6:
            record["transaction_type"] = "ILLEGAL_TYPE"

    return record


def stream_transactions(
    total_records: int,
    batch_size: int = 25000,
    seed: int = 42,
    customer_pool_size: int = 20000,
    source_system: str = "CORE_BANKING_CSV",
    error_rate: float = 0.005,
    duplicate_rate: float = 0.002,
) -> Generator[List[dict], None, Tuple[int, int, int]]:
    """
    Streaming generator yielding batches of transaction dictionaries.
    Maintains constant memory footprint regardless of total record count.
    """
    rng = random.Random(seed)
    base_time = datetime(2026, 1, 1, 0, 0, 0, tzinfo=timezone.utc)

    total_generated = 0
    total_errors_injected = 0
    total_duplicates_injected = 0

    recent_buffer: List[dict] = []
    current_batch: List[dict] = []

    for i in range(1, total_records + 1):
        should_duplicate = duplicate_rate > 0 and len(recent_buffer) > 50 and rng.random() < duplicate_rate
        if should_duplicate:
            # Re-emit a recently seen record to create a realistic duplicate
            dup_record = rng.choice(recent_buffer).copy()
            current_batch.append(dup_record)
            total_duplicates_injected += 1
            total_generated += 1
        else:
            should_error = error_rate > 0 and rng.random() < error_rate
            err_type = rng.randint(0, 6) if should_error else 0
            rec = generate_synthetic_record(
                rng=rng,
                idx=i,
                base_time=base_time,
                customer_pool_size=customer_pool_size,
                source_system=source_system,
                inject_error=should_error,
                error_type=err_type,
            )
            if should_error:
                total_errors_injected += 1
            else:
                # Keep valid records in sliding window for duplication simulation
                if len(recent_buffer) >= 2000:
                    recent_buffer.pop(0)
                recent_buffer.append(rec)

            current_batch.append(rec)
            total_generated += 1

        if len(current_batch) >= batch_size:
            yield current_batch
            current_batch = []

    if current_batch:
        yield current_batch

    return total_generated, total_errors_injected, total_duplicates_injected


def generate_to_csv(
    output_path: Path,
    total_records: int,
    batch_size: int = 25000,
    seed: int = 42,
    customer_pool_size: int = 20000,
    source_system: str = "CORE_BANKING_CSV",
    error_rate: float = 0.005,
    duplicate_rate: float = 0.002,
) -> dict:
    """Generate transactions and stream directly to a CSV file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "transaction_id",
        "source_record_id",
        "source_system",
        "customer_id",
        "transaction_timestamp",
        "transaction_amount",
        "currency",
        "transaction_type",
        "transaction_status",
        "merchant_category",
    ]

    start_time = time.monotonic()
    records_written = 0

    with open(output_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()

        generator = stream_transactions(
            total_records=total_records,
            batch_size=batch_size,
            seed=seed,
            customer_pool_size=customer_pool_size,
            source_system=source_system,
            error_rate=error_rate,
            duplicate_rate=duplicate_rate,
        )

        for batch in generator:
            writer.writerows(batch)
            records_written += len(batch)
            if records_written % 100000 == 0:
                elapsed = time.monotonic() - start_time
                print(
                    f"Generated {records_written:,} / {total_records:,} records ({records_written / elapsed:,.0f} rows/s)..."
                )

    duration = time.monotonic() - start_time
    file_size_mb = output_path.stat().st_size / (1024 * 1024)

    result = {
        "output_path": str(output_path),
        "total_records": records_written,
        "file_size_mb": round(file_size_mb, 2),
        "duration_seconds": round(duration, 3),
        "throughput_rows_per_sec": round(records_written / duration, 1) if duration > 0 else 0,
        "seed": seed,
    }

    print(
        f"\n[DONE] Successfully generated {records_written:,} records into '{output_path}'.\n"
        f"File Size: {file_size_mb:.2f} MB | Duration: {duration:.2f}s | "
        f"Rate: {result['throughput_rows_per_sec']:,.0f} records/s\n"
    )
    return result


def main():
    parser = argparse.ArgumentParser(description="Deterministic Synthetic Financial Transaction Generator")
    parser.add_argument("--records", type=int, default=100000, help="Total number of records to generate")
    parser.add_argument("--output", type=str, default="data/transactions_100k.csv", help="Output CSV path")
    parser.add_argument("--batch-size", type=int, default=25000, help="Internal generation chunk size")
    parser.add_argument("--seed", type=int, default=42, help="Deterministic random seed")
    parser.add_argument("--customer-pool", type=int, default=20000, help="Customer pool size")
    parser.add_argument("--source-system", type=str, default="CORE_BANKING_CSV", help="Source system name")
    parser.add_argument("--error-rate", type=float, default=0.005, help="Fraction of invalid records to inject")
    parser.add_argument("--duplicate-rate", type=float, default=0.002, help="Fraction of duplicate records to inject")

    args = parser.parse_args()
    out_path = Path(args.output).resolve()
    generate_to_csv(
        output_path=out_path,
        total_records=args.records,
        batch_size=args.batch_size,
        seed=args.seed,
        customer_pool_size=args.customer_pool,
        source_system=args.source_system,
        error_rate=args.error_rate,
        duplicate_rate=args.duplicate_rate,
    )


if __name__ == "__main__":
    main()
